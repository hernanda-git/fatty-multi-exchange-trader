    "CREATE OR REPLACE FUNCTION console_check_immutable_authority() RETURNS trigger "
    "LANGUAGE plpgsql AS $$\n"
    "BEGIN\n"
    " IF TG_TABLE_NAME='console_approvals' THEN\n"
    "  IF (to_jsonb(NEW)-'consumed_at') IS DISTINCT FROM (to_jsonb(OLD)-'consumed_at') "
    "THEN\n"
    "   RAISE EXCEPTION 'immutable approval authority'; END IF;\n"
    "  IF OLD.consumed_at IS NOT NULL AND NEW.consumed_at IS DISTINCT FROM "
    "OLD.consumed_at THEN\n"
    "   RAISE EXCEPTION 'approval consumption is irreversible'; END IF;\n"
    " ELSIF TG_TABLE_NAME='console_previews' THEN\n"
    "  IF (to_jsonb(NEW)-'consumed_by') IS DISTINCT FROM (to_jsonb(OLD)-'consumed_by') "
    "THEN\n"
    "   RAISE EXCEPTION 'immutable preview authority'; END IF;\n"
    "  IF OLD.consumed_by IS NOT NULL AND NEW.consumed_by IS DISTINCT FROM "
    "OLD.consumed_by THEN\n"
    "   RAISE EXCEPTION 'preview consumption is irreversible'; END IF;\n"
    " ELSIF TG_TABLE_NAME='console_step_up_grants' THEN\n"
    "  IF ((to_jsonb(NEW)-'consumed_at'-'job_id') IS DISTINCT FROM "
    "(to_jsonb(OLD)-'consumed_at'-'job_id')\n"
    "  OR (OLD.consumed_at IS NOT NULL AND\n"
    "  (NEW.consumed_at IS DISTINCT FROM OLD.consumed_at OR NEW.job_id IS DISTINCT "
    "FROM OLD.job_id))\n"
    "  OR ((NEW.consumed_at IS NULL) <> (NEW.job_id IS NULL))) THEN\n"
    "   RAISE EXCEPTION 'immutable step-up authority'; END IF;\n"
    " ELSIF TG_TABLE_NAME='console_jobs' THEN\n"
    "  IF "
    "(to_jsonb(NEW)-ARRAY['state','phase','revision','updated_at','claimed_by','lease_"
    "token','lease_until',\n"
    "  "
    "'claim_generation','effect_claimed','cancellation_requested_at','result','error',"
    "'reconciliation_required'])\n"
    "  IS DISTINCT FROM\n"
    "  "
    "(to_jsonb(OLD)-ARRAY['state','phase','revision','updated_at','claimed_by','lease_"
    "token','lease_until',\n"
    "  "
    "'claim_generation','effect_claimed','cancellation_requested_at','result','error',"
    "'reconciliation_required']) THEN\n"
    "   RAISE EXCEPTION 'immutable job authority'; END IF;\n"
    "  IF ((OLD.effect_claimed AND NOT NEW.effect_claimed) OR\n"
    "  (OLD.cancellation_requested_at IS NOT NULL AND NEW.cancellation_requested_at IS "
    "DISTINCT FROM OLD.cancellation_requested_at)\n"
    "  OR NEW.claim_generation<OLD.claim_generation OR NEW.revision<OLD.revision) THEN\n"
    "   RAISE EXCEPTION 'irreversible job fence'; END IF;\n"
    "  IF OLD.state IN "
    "('succeeded','failed','partially_succeeded','rejected','expired','cancelled') "
    "THEN\n"
    "   RAISE EXCEPTION 'immutable terminal job'; END IF;\n"
    " END IF;\n"
    " RETURN NEW;\n"
    "END $$;\n"
